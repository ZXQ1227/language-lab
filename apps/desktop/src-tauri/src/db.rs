//! SQLite data layer.
//!
//! Blueprint v1.1 decision: the database lives in the Rust core. Drizzle-ORM
//! is a build-time tool only - it authors the schema (packages/database) and
//! generates the SQL migrations embedded here. The webview never touches
//! SQLite directly; it goes through the explicit commands registered below.
//!
//! Guarantees:
//! - Migrations are tracked in `_ll_migrations` and applied exactly once.
//! - Before applying pending migrations, an automatic timestamped backup is
//!   created (keep-last-3), so an upgrade never destroys existing user data.
//! - All queries are parameterized - the commands below bind values, they
//!   never interpolate them into SQL strings.

use std::path::{Path, PathBuf};
use std::sync::Mutex;

use rusqlite::types::Value as SqlValue;
use rusqlite::{params_from_iter, Connection};
use serde_json::{Map, Number, Value as Json};

/// Versioned migrations generated by drizzle-kit (`pnpm --filter
/// @language-lab/database db:generate`). Append new entries; never edit
/// already-shipped migration SQL.
const MIGRATIONS: &[(&str, &str)] = &[(
    "0000_init",
    include_str!("../migrations/0000_square_rictor.sql"),
)];

const MAX_BACKUPS: usize = 3;

pub struct Db {
    pub conn: Mutex<Connection>,
    pub path: PathBuf,
}

impl Db {
    pub fn open(path: &Path) -> rusqlite::Result<Self> {
        Ok(Db {
            conn: Mutex::new(Connection::open(path)?),
            path: path.to_path_buf(),
        })
    }
}

fn to_sql(v: Json) -> Result<SqlValue, String> {
    Ok(match v {
        Json::Null => SqlValue::Null,
        Json::Bool(b) => SqlValue::Integer(if b { 1 } else { 0 }),
        Json::Number(n) => {
            if let Some(i) = n.as_i64() {
                SqlValue::Integer(i)
            } else {
                SqlValue::Real(n.as_f64().ok_or("invalid number")?)
            }
        }
        Json::String(s) => SqlValue::Text(s),
        // Structured values are stored as JSON text (columns like payload).
        other => SqlValue::Text(other.to_string()),
    })
}

fn to_json(v: SqlValue) -> Json {
    match v {
        SqlValue::Null => Json::Null,
        SqlValue::Integer(i) => Json::Number(Number::from(i)),
        SqlValue::Real(f) => Number::from_f64(f).map(Json::Number).unwrap_or(Json::Null),
        SqlValue::Text(s) => Json::String(s),
        SqlValue::Blob(b) => Json::Array(b.into_iter().map(|byte| Json::Number(byte.into())).collect()),
    }
}

/// Creates a consistent backup of the database into `dest` using SQLite's
/// online backup API (safe even while the connection is open).
fn backup_to(source: &Connection, dest: &Path) -> Result<(), String> {
    let mut out =
        Connection::open(dest).map_err(|e| format!("open backup target failed: {e}"))?;
    let backup =
        rusqlite::backup::Backup::new(source, &mut out).map_err(|e| format!("backup init: {e}"))?;
    backup
        .run_to_completion(64, std::time::Duration::from_millis(5), None)
        .map_err(|e| format!("backup failed: {e}"))
}

fn prune_backups(dir: &Path) {
    let mut files: Vec<PathBuf> = match std::fs::read_dir(dir) {
        Ok(entries) => entries
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|ext| ext == "db"))
            .collect(),
        Err(_) => return,
    };
    files.sort();
    while files.len() > MAX_BACKUPS {
        let oldest = files.remove(0);
        let _ = std::fs::remove_file(oldest);
    }
}

/// Applies pending migrations. Returns the number applied.
/// Before the first pending migration runs, a timestamped backup is written.
pub fn run_migrations(conn: &Connection, db_path: &Path) -> Result<usize, String> {
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS _ll_migrations (
             name TEXT PRIMARY KEY,
             applied_at INTEGER NOT NULL
         );",
    )
    .map_err(|e| format!("create migration table failed: {e}"))?;

    let mut applied: Vec<String> = Vec::new();
    {
        let mut stmt = conn
            .prepare("SELECT name FROM _ll_migrations")
            .map_err(|e| format!("read migrations failed: {e}"))?;
        let mut rows = stmt.query([]).map_err(|e| e.to_string())?;
        while let Some(row) = rows.next().map_err(|e| e.to_string())? {
            applied.push(row.get::<_, String>(0).map_err(|e| e.to_string())?);
        }
    }

    let pending: Vec<&(&str, &str)> = MIGRATIONS
        .iter()
        .filter(|(name, _)| !applied.iter().any(|a| a == name))
        .collect();

    if pending.is_empty() {
        return Ok(0);
    }

    // Pre-migration safety net: back up current user data before any change.
    // Skipped on first launch (no domain tables yet = nothing to lose).
    let has_domain_tables: i64 = conn
        .query_row(
            "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name != '_ll_migrations'",
            [],
            |r| r.get(0),
        )
        .map_err(|e| e.to_string())?;
    if has_domain_tables > 0 && db_path.exists() {
        let backup_dir = db_path.parent().unwrap_or(Path::new(".")).join("backups");
        std::fs::create_dir_all(&backup_dir).map_err(|e| format!("create backup dir: {e}"))?;
        let stamp = chrono_now();
        let dest = backup_dir.join(format!("pre-migration-{stamp}.db"));
        backup_to(conn, &dest)?;
        prune_backups(&backup_dir);
    }

    let mut count = 0;
    for (name, sql) in pending {
        conn.execute_batch(sql)
            .map_err(|e| format!("migration {name} failed: {e}"))?;
        conn.execute(
            "INSERT INTO _ll_migrations (name, applied_at) VALUES (?1, ?2)",
            rusqlite::params![name, now_ms()],
        )
        .map_err(|e| format!("record migration {name} failed: {e}"))?;
        count += 1;
    }
    Ok(count)
}

fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

/// Wall-clock timestamp string used in backup filenames (UTC, no external
/// dependencies).
fn chrono_now() -> String {
    let secs = now_ms() / 1000;
    let days = secs / 86_400;
    let rem = secs % 86_400;
    let (h, m, s) = (rem / 3600, (rem % 3600) / 60, rem % 60);
    // civil-from-days algorithm (Howard Hinnant)
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = doe.div_euclid(365);
    let y = era * 400 + yoe;
    let doy = doe.rem_euclid(365);
    let mp = doy.div_euclid(30);
    let d = doy.rem_euclid(30) + 1;
    let mth = if mp < 10 { mp + 3 } else { mp - 9 };
    let yr = if mth <= 2 { y + 1 } else { y };
    format!("{yr:04}-{mth:02}-{d:02}T{h:02}{m:02}{s:02}Z")
}

