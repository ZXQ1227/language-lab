#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicU32, Ordering};

    static TEST_SEQ: AtomicU32 = AtomicU32::new(0);

    fn temp_db(label: &str) -> (Connection, PathBuf) {
        let dir = std::env::temp_dir().join(format!(
            "language-lab-test-{}-{}",
            std::process::id(),
            TEST_SEQ.fetch_add(1, Ordering::SeqCst)
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join(format!("{label}.db"));
        (Connection::open(&path).unwrap(), path)
    }

    fn count_tables(conn: &Connection) -> i64 {
        conn.query_row(
            "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE '\\_%' ESCAPE '\\'",
            [],
            |r| r.get(0),
        )
        .unwrap()
    }

    #[test]
    fn migrations_create_all_tables() {
        let (conn, path) = temp_db("migrate");
        let applied = run_migrations(&conn, &path).unwrap();
        assert_eq!(applied, MIGRATIONS.len());
        // 11 domain tables (the migration bookkeeping table is excluded by
        // the count query's LIKE filter).
        assert_eq!(count_tables(&conn), 11);
        assert!(count_tables(&conn) > 0);
        // Re-running is a no-op
        assert_eq!(run_migrations(&conn, &path).unwrap(), 0);
    }

    #[test]
    fn data_persists_across_reopen() {
        let (_, path) = temp_db("persist");
        {
            let conn = Connection::open(&path).unwrap();
            run_migrations(&conn, &path).unwrap();
            conn.execute(
                "INSERT INTO users (id, display_name, created_at, updated_at) VALUES (?1, ?2, 1, 1)",
                rusqlite::params!["u1", "Tester"],
            )
            .unwrap();
        }
        // Simulate app restart: fresh connection, migrations must not clobber data.
        let conn = Connection::open(&path).unwrap();
        run_migrations(&conn, &path).unwrap();
        let name: String = conn
            .query_row("SELECT display_name FROM users WHERE id='u1'", [], |r| r.get(0))
            .unwrap();
        assert_eq!(name, "Tester");
    }

    #[test]
    fn pre_migration_backup_is_created() {
        let (_, path) = temp_db("backup");
        {
            let conn = Connection::open(&path).unwrap();
            run_migrations(&conn, &path).unwrap();
            conn.execute(
                "INSERT INTO users (id, display_name, created_at, updated_at) VALUES (?1, ?2, 1, 1)",
                rusqlite::params!["u1", "Tester"],
            )
            .unwrap();
            // Force the migration to be pending again so the next
            // run_migrations call takes the "upgrade" path.
            conn.execute_batch("DELETE FROM _ll_migrations;").unwrap();
            // The re-run will fail (tables already exist) - but the backup
            // must be written BEFORE the migration SQL executes.
            let result = run_migrations(&conn, &path);
            assert!(result.is_err(), "re-applied migration should conflict");
        }
        let backup_dir = path.parent().unwrap().join("backups");
        let files: Vec<_> = std::fs::read_dir(&backup_dir)
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .collect();
        assert!(!files.is_empty(), "expected pre-migration backup files");
        // The backup must contain the pre-migration user data.
        let backup = Connection::open(&files[0]).unwrap();
        let name: String = backup
            .query_row("SELECT display_name FROM users WHERE id='u1'", [], |r| r.get(0))
            .unwrap();
        assert_eq!(name, "Tester");
    }

    #[test]
    fn backup_and_restore_roundtrip() {
        let (mut conn, path) = temp_db("restore");
        run_migrations(&conn, &path).unwrap();
        conn.execute(
            "INSERT INTO users (id, display_name, created_at, updated_at) VALUES (?1, ?2, 1, 1)",
            rusqlite::params!["u1", "Before"],
        )
        .unwrap();

        let backup_dir = path.parent().unwrap().join("backups");
        std::fs::create_dir_all(&backup_dir).unwrap();
        let dest = backup_dir.join("manual.db");
        backup_to(&conn, &dest).unwrap();

        // Change data after backup.
        conn.execute(
            "UPDATE users SET display_name='After' WHERE id='u1'",
            [],
        )
        .unwrap();

        // Restore into the live connection (same behavior as db_restore).
        {
            let source = Connection::open(&dest).unwrap();
            let backup = rusqlite::backup::Backup::new(&source, &mut conn).unwrap();
            backup
                .run_to_completion(64, std::time::Duration::from_millis(5), None)
                .unwrap();
        }

        let name: String = conn
            .query_row("SELECT display_name FROM users WHERE id='u1'", [], |r| r.get(0))
            .unwrap();
        assert_eq!(name, "Before");
    }
}
