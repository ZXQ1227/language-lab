type CmdResult<T> = Result<T, String>;

/// Executes a parameterized statement; returns affected rows and last insert id.
#[tauri::command]
pub fn db_execute(db: tauri::State<Db>, sql: String, params: Vec<Json>) -> CmdResult<Json> {
    let conn = db.conn.lock().map_err(|e| e.to_string())?;
    let values: Vec<SqlValue> = params
        .into_iter()
        .map(to_sql)
        .collect::<Result<_, _>>()
        .map_err(|e| format!("invalid param: {e}"))?;
    let affected = conn
        .execute(&sql, params_from_iter(values))
        .map_err(|e| format!("db_execute failed: {e}"))?;
    Ok(Json::Object(
        [
            ("rowsAffected".into(), Json::Number(affected.into())),
            (
                "lastInsertId".into(),
                Json::String(conn.last_insert_rowid().to_string()),
            ),
        ]
        .into_iter()
        .collect(),
    ))
}

/// Runs a parameterized SELECT; returns rows as JSON objects (column name -> value).
#[tauri::command]
pub fn db_select(db: tauri::State<Db>, sql: String, params: Vec<Json>) -> CmdResult<Vec<Json>> {
    let conn = db.conn.lock().map_err(|e| e.to_string())?;
    let mut stmt = conn
        .prepare(&sql)
        .map_err(|e| format!("db_select prepare failed: {e}"))?;
    let col_names: Vec<String> = stmt.column_names().iter().map(|s| s.to_string()).collect();
    let values: Vec<SqlValue> = params
        .into_iter()
        .map(to_sql)
        .collect::<Result<_, _>>()
        .map_err(|e| format!("invalid param: {e}"))?;
    let mut rows = stmt
        .query(params_from_iter(values))
        .map_err(|e| format!("db_select query failed: {e}"))?;
    let mut out: Vec<Json> = Vec::new();
    while let Some(row) = rows.next().map_err(|e| format!("db_select row: {e}"))? {
        let mut obj = Map::new();
        for (i, name) in col_names.iter().enumerate() {
            let raw: SqlValue = row
                .get(i)
                .map_err(|e| format!("db_select column {name}: {e}"))?;
            obj.insert(name.clone(), to_json(raw));
        }
        out.push(Json::Object(obj));
    }
    Ok(out)
}

/// Database status for health checks / diagnostics.
#[tauri::command]
pub fn db_status(db: tauri::State<Db>) -> CmdResult<Json> {
    let conn = db.conn.lock().map_err(|e| e.to_string())?;
    let applied: i64 = conn
        .query_row("SELECT COUNT(*) FROM _ll_migrations", [], |r| r.get(0))
        .map_err(|e| e.to_string())?;
    let tables: i64 = conn
        .query_row(
            "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE '\\_%' ESCAPE '\\'",
            [],
            |r| r.get(0),
        )
        .map_err(|e| e.to_string())?;
    Ok(Json::Object(
        [
            ("ok".into(), Json::Bool(true)),
            ("migrationsApplied".into(), Json::Number(applied.into())),
            ("tables".into(), Json::Number(tables.into())),
            (
                "path".into(),
                Json::String(db.path.display().to_string()),
            ),
        ]
        .into_iter()
        .collect(),
    ))
}

/// Manual backup; returns the backup file path.
#[tauri::command]
pub fn db_backup(db: tauri::State<Db>) -> CmdResult<Json> {
    let conn = db.conn.lock().map_err(|e| e.to_string())?;
    let backup_dir = db.path.parent().unwrap_or(Path::new(".")).join("backups");
    std::fs::create_dir_all(&backup_dir).map_err(|e| format!("create backup dir: {e}"))?;
    let dest = backup_dir.join(format!("manual-{}.db", chrono_now()));
    backup_to(&conn, &dest)?;
    prune_backups(&backup_dir);
    Ok(Json::Object(
        [(
            "path".into(),
            Json::String(dest.display().to_string()),
        )]
        .into_iter()
        .collect(),
    ))
}

/// Restores the database from a backup file (SQLite online restore - the
/// destination connection stays usable).
#[tauri::command]
pub fn db_restore(db: tauri::State<Db>, source_path: String) -> CmdResult<Json> {
    let source = Connection::open(&source_path).map_err(|e| format!("open source failed: {e}"))?;
    let mut conn = db.conn.lock().map_err(|e| e.to_string())?;
    let backup = rusqlite::backup::Backup::new(&source, &mut conn)
        .map_err(|e| format!("restore init: {e}"))?;
    backup
        .run_to_completion(64, std::time::Duration::from_millis(5), None)
        .map_err(|e| format!("restore failed: {e}"))?;
    Ok(Json::Object(
        [("restored".into(), Json::Bool(true))].into_iter().collect(),
    ))
}

